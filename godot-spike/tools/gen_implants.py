#!/usr/bin/env python3
"""Writes src/implant_data.gd from the implant spreadsheet (tools/content/implant_catalogue.xlsx, tab "Example Implants").
Only tiers 1 to 3 (Basic, Improved, Quality) go into the game; Military (4) and Prototype (5) stay out for now.
The sheet must hold calculated values (open and save it once in a spreadsheet program).   Run: python3 tools/gen_implants.py"""
import os, re
from openpyxl import load_workbook
HERE = os.path.dirname(os.path.abspath(__file__))
MAX_TIER = 3
PART = {"Head / cortex": "head", "Eyes": "eyes", "Spine": "spine", "Chest / organs": "chest", "Dermal": "dermal", "Arms": "arms", "Hands": "hands", "Legs": "legs"}
GROUP = {"head": "head", "chest": "chest", "arms": "arms", "legs": "legs", "all limbs": "all"}
def num(s):
    return int(s) if float(s) == int(float(s)) else float(s)
def parse_skills(t):
    out = {}
    for chunk in (t or "").split(";"):
        m = re.match(r"\s*([A-Za-z]+) ([+-]\d+)", chunk)
        if m:
            out[m.group(1).lower()] = int(m.group(2))
    return out
def parse_req(t):
    out = {}
    for chunk in (t or "").split(";"):
        m = re.match(r"\s*([A-Za-z]+) (\d+)", chunk)
        if m:
            out[m.group(1).lower()] = int(m.group(2))
    return out
def catalogue():
    wb = load_workbook(os.path.join(HERE, "content/implant_catalogue.xlsx"), data_only=True)
    ws = wb["Example Implants"]
    rows = []
    for r in ws.iter_rows(min_row=2, values_only=True):
        if not r[0] or int(r[3]) > MAX_TIER:
            continue
        if r[9] is None or r[11] is None:
            raise SystemExit("the sheet has no calculated values: open and save it in a spreadsheet program first")
        iid = r[1].replace("trl_imp_", "")
        d = {"id": iid, "part": PART[r[2]], "name": r[0], "cost": int(r[4]), "live": True, "grade": int(r[3]),
             "armor": int(r[6]), "armor_group": GROUP[r[7]], "dur": int(r[8]), "draw": float(r[9])}
        if r[10]:
            d["battery"] = int(r[10])
        sk = parse_skills(r[14])
        if sk:
            d["skills"] = sk
        if r[15]:
            d["nano"] = int(r[15])
        rq = parse_req(r[16])
        if rq:
            d["req"] = rq
        d["note"] = (r[17] or "")
        rows.append(d)
    # a Trilobit holds about a third of the battery of its tier's chest implant (the Lung Pack / Heart Pump, not the Reserve Cell)
    std = {}
    for d in rows:
        if d["part"] == "chest" and "battery" in d:
            std[d["grade"]] = min(std.get(d["grade"], 10 ** 9), d["battery"])
    for d in rows:
        if d["part"] == "head" and "battery" not in d and d["grade"] in std:
            d["battery"] = int(round(std[d["grade"]] / 3.0))
    return rows
def lit(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, dict):
        return "{" + ", ".join('"%s": %s' % (k, lit(x)) for k, x in v.items()) + "}"
    if isinstance(v, str):
        return '"%s"' % v.replace("\\", "\\\\").replace('"', '\\"')
    return repr(v)
if __name__ == "__main__":
    rows = catalogue()
    out = ["extends RefCounted", "## GENERATED by tools/gen_implants.py from tools/content/implant_catalogue.xlsx - do not edit by hand.",
           "## Tiers 1-3 (Basic, Improved, Quality).  Fields: id, part, name, cost, live, grade (= tier), armor + armor_group + dur, draw (kJ/h, latent),",
           "## battery (kJ: chest implants, and a third of that in each Trilobit), skills ({skill id: bonus}), nano (nanohack slots, Trilobits only), req ({skill id: level} needed to fit it), note.",
           "const ALL := ["]
    for d in rows:
        out.append("\t" + lit(d) + ",")
    out.append("]")
    open(os.path.join(HERE, "../src/implant_data.gd"), "w").write("\n".join(out) + "\n")
    print(len(rows), "implants")
