"""Writes src/furniture_gen.gd (the new tile table) and docs/furniture_list.md from tools/content/furniture_list.py"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, 'content'))
import furniture_list as F
root = os.path.dirname(here)
rows = []
for fid, label, cat, hexc in F.FLOORS:
    rows.append('\t["%s", "t_trl_%s", 1, 0],' % (fid, fid))
for fid, label, cat, walk, cover, hexc in F.FURN:
    rows.append('\t["%s", "f_trl_%s", %d, %d],' % (fid, fid, walk, cover))
open(os.path.join(root, 'src', 'furniture_gen.gd'), 'w').write(
    '## GENERATED by tools/gen_furniture.py from tools/content/furniture_list.py: do not edit.  New floors and furniture: [name, sprite, walkable, low cover]\nconst NEW := [\n' + '\n'.join(rows) + '\n]\n')
os.makedirs(os.path.join(root, 'docs'), exist_ok=True)
md = ['# Trilobit furniture list (new)', '', 'Scenery only: none of these has stats or a function yet.  Sprites are placeholders (a coloured slab with initials) until the real art is drawn.',
      'Tile id = the name; sprite file = `f_trl_<id>` (furniture) or `t_trl_<id>` (floors).', '', '## Floors', '', '| id | name |', '|---|---|']
for fid, label, cat, hexc in F.FLOORS:
    md.append('| %s | %s |' % (fid, label))
cats = []
for f in F.FURN:
    if f[2] not in cats:
        cats.append(f[2])
for c in cats:
    md += ['', '## Furniture: ' + c, '', '| id | name | walkable | low cover |', '|---|---|---|---|']
    for fid, label, cat, walk, cover, hexc in F.FURN:
        if cat == c:
            md.append('| %s | %s | %s | %s |' % (fid, label, 'yes' if walk else 'no', 'yes' if cover else 'no'))
md.append('')
md.append('Total: %d floors, %d furniture pieces.' % (len(F.FLOORS), len(F.FURN)))
open(os.path.join(root, 'docs', 'furniture_list.md'), 'w').write('\n'.join(md) + '\n')
print(len(F.FLOORS), len(F.FURN))
